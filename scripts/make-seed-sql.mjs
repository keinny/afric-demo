// Builds supabase/seed.sql from the app's own sample data (src/seed.js).
// Run:  npm run seed:sql
import { writeFileSync } from 'node:fs';
import { makeSeed } from '../src/seed.js';
import { TABLES, toRow } from '../src/dbmap.js';

const s = makeSeed();

const lit = (v) => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'object') return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};

const insert = (table, rows) => {
  if (!rows.length) return '';
  const cols = [...new Set(rows.flatMap((r) => Object.keys(r)))];
  const values = rows.map((r) => `  (${cols.map((c) => lit(r[c])).join(', ')})`).join(',\n');
  return `insert into public.${table} (${cols.join(', ')}) values\n${values}\non conflict (id) do nothing;\n\n`;
};

let sql = `-- Sample data for the Africo Cash Advance LMS demo.
-- Generated by scripts/make-seed-sql.mjs on ${new Date().toISOString().slice(0, 10)}. Dates are relative to that day.
-- Run AFTER schema.sql, in Supabase → SQL Editor. Safe to re-run (existing ids are skipped).
-- All people, phone numbers and NRC numbers here are fictional.

`;

for (const [key, table] of Object.entries(TABLES)) {
  sql += `-- ${table}\n` + insert(table, (s[key] || []).map((r) => toRow(r)));
}
sql += '-- notification_rules\n' + insert('notification_rules', Object.entries(s.rules).map(([id, enabled]) => ({ id, enabled })));
sql += '-- settings (single row)\n' + insert('settings', [{ id: 1, ...toRow(s.settings) }]);

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql);
console.log(`supabase/seed.sql written (${sql.length} bytes)`);
